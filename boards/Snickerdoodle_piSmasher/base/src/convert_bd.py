#!/usr/bin/env python3
"""Convert krtkl's Vivado 2018.2 piSmasher 4.1 hdmi-pass-through block design
script into one that builds in current Vivado.

* keeps only the hierarchy and root-design procs (no version/IP checks)
* resolves every IP VLNV to the newest version in the running Vivado
* drops the system_ila debug cores and their probe connections
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()

body = text[text.index("proc create_hier_cell_hdmi_audio"):]
body = body[:body.rindex('create_root_design ""')]

body = re.sub(r"-vlnv xilinx\.com:ip:([a-z0-9_]+):[0-9.]+",
              r"-vlnv [pynq_latest_vlnv \1]", body)

body = re.sub(r"\n  # Create instance: \w*ila\w*, and set properties\n"
              r"  set (\w*ila\w*) \[ create_bd_cell [^\n]*\n"
              r"(  set_property -dict \[ list \\\n(?:   [^\n]*\n)*? \] \$\1\n)?",
              "\n", body)
body = re.sub(r" \[get_bd_pins (?:hdmi_ila|system_ila_\d+)/\w+\]", "", body)
assert "system_ila" not in body and "hdmi_ila" not in body, "ILA removal failed"

header = '''# Generated by convert_bd.py from krtkl piSmasher-testing
# piSmasher_4.1/hdmi-pass-through (Vivado 2018.2). Do not edit by hand.

proc pynq_latest_vlnv { name } {
  set defs [lsort -dictionary [get_ipdefs -all xilinx.com:ip:${name}:*]]
  if { [llength $defs] == 0 } { error "IP ${name} not found" }
  return [lindex $defs end]
}

'''
open(dst, "w").write(header + body)
